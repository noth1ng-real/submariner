int AESDecrypt(char * payload, DWORD payload_len, unsigned char * key, size_t keylen) {
    HCRYPTPROV hProv;
    HCRYPTHASH hHash;
    HCRYPTKEY hKey;

    // Accquire handle to cryptographic provider
    if(!CryptAcquireContextW(&hProv, NULL, NULL, PROV_RSA_AES, CRYPT_VERIFYCONTEXT)) return -1;

    // Create SHA-256 hash object
    if(!CryptCreateHash(hProv, CALG_SHA_256, 0, 0, &hHash)) return -1;

    // Feed the key bytes into SHA-256 hash object
    if(!CryptHashData(hHash, (BYTE*)key, (DWORD)keylen, 0)) return -1;

    //Derive AES-256 key from SHA-256 hash
    if(!CryptDeriveKey(hProv, CALG_AES_256, hHash, 0, &hKey)) return -1;

    BYTE iv[16] = {0};
    if(!CryptSetKeyParam(hKey, KP_IV, iv, 0)) return -1;

    // Decrypt payload buffer in place using AES key
    if(!CryptDecrypt(hKey, (HCRYPTHASH) NULL, 1, 0, (BYTE*) payload, &payload_len)) return -1;

    // Cleanup
    CryptReleaseContext(hProv, 0);
    CryptDestroyHash(hHash);
    CryptDestroyKey(hKey);

    return 0;
}

